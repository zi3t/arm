// Writes build/gluon.h (the GLUON joints, parsed from gluon.urdf exactly as
// kinematics.test.js parses them) for the viewer and tests, and build/fixture.h
// (the recorded Rust fixture) for kinematics_test.c. JS number strings
// round-trip, so C reads the same doubles.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const read = (name) => readFileSync(new URL(name, import.meta.url), "utf8");
const fixture = JSON.parse(read("../kinematics.fixture.json"));
const joints = [...read("../gluon.urdf").matchAll(/<joint[\s\S]*?<\/joint>/g)].map((m) => m[0])
  .filter((xml) => /type="revolute"/.test(xml)).map((xml) => {
    const triple = (re) => xml.match(re)[1].trim().split(/\s+/).map(Number);
    const value = (name) => Number(xml.match(new RegExp(`${name}="([^"]+)"`))[1]);
    return { origin: triple(/<origin\s+xyz="([^"]+)"/), axis: triple(/<axis\s+xyz="([^"]+)"/), lower: value("lower"), upper: value("upper"), velocity: value("velocity") };
  });

const num = (v) => (typeof v === "boolean" ? (v ? "true" : "false") : String(v));
const list = (values) => `{${values.map(num).join(", ")}}`;
const checkpoints = (rows) => list(rows.map((c) => `{${c.step}, ${list(c.q)}, ${c.flags}, ${c.limited}}`));
const run = (r) => `  {${num(r.positionOnly)}, ${list(r.start)}, ${list(r.twist ?? [0, 0, 0, 0, 0, 0])}, ${checkpoints(r.checkpoints)}, ${r.checkpoints.length}, ${r.flagsOr}}`;

const gluon = `// Generated by gen-fixture.mjs from gluon.urdf. Do not edit.
#include "../kinematics.h"

enum { GLUON_JOINTS = ${joints.length} };
static const ArmJoint GLUON[GLUON_JOINTS] = {
${joints.map((j) => `  {${list(j.origin)}, ${list(j.axis)}, ${num(j.lower)}, ${num(j.upper)}, ${num(j.velocity)}}`).join(",\n")}
};
`;

const out = `// Generated by gen-fixture.mjs from kinematics.fixture.json. Do not edit.
#include <stdbool.h>
#include "gluon.h"

enum { FK_ROWS = ${fixture.fk.length}, JOG_ROWS = ${fixture.jog.length}, VARYING_ROWS = ${fixture.varying.length} };
static const double JOG_DT = ${num(fixture.jogDt)};

typedef struct { double q[6], links[42], tcp[3], trust[2]; } FkRow;
static const FkRow FK[] = {
${fixture.fk.map((r) => `  {${list(r.q)}, ${list(r.links)}, ${list(r.tcp)}, ${list(r.trust)}}`).join(",\n")}
};

typedef struct { int step; double q[6]; int flags, limited; } Checkpoint;
typedef struct { bool position_only; double start[6], twist[6]; Checkpoint checkpoints[4]; int count, flags_or; } JogRun;
static const JogRun JOG[] = {
${fixture.jog.map(run).join(",\n")}
};
static const JogRun VARYING[] = {
${fixture.varying.map(run).join(",\n")}
};
`;
mkdirSync(new URL("./build/", import.meta.url), { recursive: true });
writeFileSync(new URL("./build/gluon.h", import.meta.url), gluon);
writeFileSync(new URL("./build/fixture.h", import.meta.url), out);
